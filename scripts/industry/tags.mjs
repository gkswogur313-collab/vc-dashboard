const ASCII = /^[a-z0-9&]+$/
export function tagTitle(title) {
  const t = ` ${(title || '').toLowerCase()} `
  const out = []
  for (const [tag, kws] of TAGS) {
    for (const k of kws) {
      // 짧은 영문 키워드(ai, ip, gpu 등)는 단어 경계로만 매칭(예: 'mail'의 ai 오탐 방지)
      const hit = ASCII.test(k) ? new RegExp(`(^|[^a-z])${k.replace(/&/g, '\\&')}([^a-z]|$)`).test(t) : t.includes(k)
      if (hit) { out.push(tag); break }
    }
  }
  return out
}
